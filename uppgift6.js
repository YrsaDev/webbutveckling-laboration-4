"use strict";
// Calculates and returns the area of a rectangle
function calculateArea(width, height) {
    const area = width * height;
    return area;
}
// Calls the function with different values and prints the results
console.log(calculateArea(5, 4));
console.log(calculateArea(9, 6));
console.log(calculateArea(12, 7));